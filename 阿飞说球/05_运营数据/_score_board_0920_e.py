# -*- coding: utf-8 -*-
"""比分盘 → 让球落点 归类(修正版)

⚠️ 本文件修正了一个我自己的错误: 上一版把 `1:0`/`2:1`/`3:2` 归进了"走水" ——
   那是**主队(富勒姆)赢球**, 在 +1 线里属于**让胜(受让方不败)**。
   +1 线的"走水"只能是**客队恰好赢 1 球**: 0:1 / 1:2 / 2:3。
"""
# 比分 → 赔率 (09-18 09:45)
ODDS = {
    (1, 0): 16.00, (2, 0): 24.00, (2, 1): 10.50, (3, 0): 50.00, (3, 1): 23.00, (3, 2): 25.00,
    (4, 0): 150.0, (4, 1): 75.00, (4, 2): 80.00, (5, 0): 450.0, (5, 1): 300.0, (5, 2): 300.0,
    (0, 0): 20.00, (1, 1): 8.00, (2, 2): 11.00, (3, 3): 35.00,
    (0, 1): 10.50, (0, 2): 11.00, (1, 2): 7.50, (0, 3): 18.00, (1, 3): 12.00, (2, 3): 18.00,
    (0, 4): 35.00, (1, 4): 25.00, (2, 4): 36.00, (0, 5): 100.0, (1, 5): 65.00, (2, 5): 90.00,
}
OTHER = {'胜其它': 70.00, '平其它': 150.0, '负其它': 30.00}

inv = {k: 1 / v for k, v in ODDS.items()}
inv.update({k: 1 / v for k, v in OTHER.items()})
S = sum(inv.values())
p = {k: v / S for k, v in inv.items()}

print('比分盘去水(抽水 %.4f)' % S)
top = sorted([kv for kv in p.items() if isinstance(kv[0], tuple)], key=lambda x: -x[1])[:6]
print('  最热六档: ' + '  '.join('%d:%d %.1f%%' % (h, a, v * 100) for (h, a), v in top))
print()

win = push = lose = 0.0
for k, v in p.items():
    if k == '胜其它':                       # 主队大胜
        win += v
        continue
    if k == '平其它':                       # 平局(高比分)
        win += v                            # +1 后主队赢盘
        continue
    if k == '负其它':                       # 客队大胜
        lose += v
        continue
    h, a = k
    net = h + 1 - a                          # +1 线: 主队受让一球
    if net > 0:
        win += v
    elif net == 0:
        push += v
    else:
        lose += v

print('比分盘 → +1 线落点:')
print('  让胜(富勒姆不败) = %.1f%%' % (win * 100))
print('  走水(曼联恰好赢1) = %.1f%%' % (push * 100))
print('  让负(曼联赢2+)    = %.1f%%' % (lose * 100))
print()
print('走水明细(只能是客队恰好赢1球):')
for k in [(0, 1), (1, 2), (2, 3)]:
    print('  %d:%d  %.1f%%' % (k[0], k[1], p[k] * 100))
print('  (1:0 / 2:1 / 3:2 是主队赢球 -> 让胜; 上一版误归走水)')
print()
print('三个来源对照:')
print('  %-22s %8s %8s %8s' % ('来源', '让胜', '走水', '让负'))
print('  %-22s %7.1f%% %7.1f%% %7.1f%%' % ('让球胜平负盘(去水)', 47.96, 24.31, 27.73))
print('  %-22s %7.1f%% %7.1f%% %7.1f%%' % ('比分盘归类', win * 100, push * 100, lose * 100))
print('  %-22s %7.1f%% %7.1f%% %7.1f%%' % ('模型(+1 线)', 56.7, 19.4, 24.0))
