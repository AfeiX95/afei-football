BASE = {(-1,): (0.27, 0.23, 0.50), (+1,): (0.32, 0.23, 0.45)}


def parse_3(s):
    """'01.853.103.75' -> [1.85, 3.10, 3.75]"""
    out = []
    i = 0
    while i < len(s):
        j = s.index('.', i)
        k = j + 3
        out.append(float(s[i:k]))
        i = k
    return out


def dewater(o):
    inv = [1 / x for x in o]
    s = sum(inv)
    return [x / s * 100 for x in inv], s


def side_names(line):
    if line < 0:
        return ('让球方(主队)赢够', '走水', '受让方(客队)赢盘')
    return ('受让方(主队)不败', '走水', '让球方(客队)赢够')


